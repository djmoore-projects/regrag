"""Render eval/results/*.json into eval/results/REPORT.md (numbers come only from run files).

    python -m eval.report
"""

from __future__ import annotations

import json
from pathlib import Path

RESULTS = Path(__file__).parent / "results"
MODE_NAMES = {
    "dense": "Dense only (pgvector)",
    "bm25": "BM25 only",
    "hybrid": "Hybrid (RRF)",
    "dense_rerank": "Dense + rerank",
    "hybrid_rerank": "**Hybrid + rerank (default)**",
}


def fmt(v) -> str:
    return "–" if v is None else (f"{v:.3f}" if isinstance(v, float) else str(v))


def _row(name: str, m: dict) -> str:
    return (f"| {name} | {fmt(m['recall@1'])} | {fmt(m['recall@3'])} | {fmt(m['recall@8'])} | "
            f"{fmt(m['mrr'])} | {fmt(m['ndcg@8'])} | {m['latency_p50_ms'] / 1000:.1f} s |")


def retrieval_section(base: dict, final: dict | None, fast: dict | None) -> list[str]:
    """base: no structural boosts (all modes); final: rerank modes with boosts; fast: small reranker."""
    lines = [
        "## Retrieval ablation",
        "",
        f"{base['n_answerable']} answerable golden questions · embeddings `{base['embed_model']}` · "
        f"reranker `{base['rerank_model']}` (pool {base.get('rerank_pool', 30)}) · relevance judged on gold "
        "paragraph labels · latency is CPU-only on a laptop.",
        "",
        "| Configuration | Recall@1 | Recall@3 | Recall@8 | MRR | nDCG@8 | p50 retrieval |",
        "|---|---|---|---|---|---|---|",
    ]
    for mode, m in base["modes"].items():
        lines.append(_row(MODE_NAMES.get(mode, mode).replace("**", "").replace(" (default)", ""), m))
    if final:
        for mode, m in final["modes"].items():
            name = MODE_NAMES.get(mode, mode).replace("**", "").replace(" (default)", "")
            label = f"{name} + structural boosts"
            lines.append(_row(f"**{label} (default)**" if mode == "hybrid_rerank" else label, m))
    if fast:
        m = fast["modes"]["hybrid_rerank"]
        lines.append(_row(f"Fast profile: `{fast['rerank_model'].split('/')[-1]}`, pool {fast['rerank_pool']}", m))
    ref = (final or base)["modes"].get("hybrid_rerank")
    dense = base["modes"].get("dense")
    if ref and dense:
        lines += ["", "Recall@8 by question category (dense only → default pipeline):", "",
                  "| Category | n | Dense | Default |", "|---|---|---|---|"]
        for cat, v in ref["by_category"].items():
            d = dense["by_category"].get(cat, {})
            lines.append(f"| {cat} | {v['n']} | {fmt(d.get('recall@8'))} | {fmt(v['recall@8'])} |")
    ab = (final or base).get("abstention")
    if ab:
        ans, un = ab["answerable_top_scores"], ab["unanswerable_top_scores"]
        cal = ab["calibration"]
        lines += ["", "**Abstention.** Top rerank score, answerable vs out-of-corpus: "
                  f"min answerable {min(ans):.2f}; out-of-corpus {', '.join(f'{x:.2f}' for x in sorted(un))}. "
                  f"The balanced-accuracy optimum ({cal['threshold']:.2f}) would refuse "
                  f"{1 - cal['answer_rate_answerable']:.0%} of answerable questions, so the shipped threshold is "
                  f"0.0: no answerable question is refused, {sum(x < 0 for x in un)}/{len(un)} out-of-corpus "
                  "questions are declined before any LLM call, and the rest rely on the model declining."]
    return lines


def rag_section(r: dict) -> list[str]:
    lines = [
        "## End-to-end (Ragas)",
        "",
        f"Generator `{r['generator']}` · judge `{r['judge']}` (different model, to avoid self-preference).",
        "",
        "| Mode | Faithfulness | Context recall | Answer relevancy | Citation coverage | Answers answerable | Declines out-of-corpus |",
        "|---|---|---|---|---|---|---|",
    ]
    for m in r["results"]:
        lines.append(
            f"| {MODE_NAMES.get(m['mode'], m['mode'])} | {fmt(m['faithfulness'])} | {fmt(m['context_recall'])} | "
            f"{fmt(m['answer_relevancy'])} | {fmt(m['citation_coverage'])} | {fmt(m['answer_rate_answerable'])} | "
            f"{fmt(m['abstain_rate_unanswerable'])} |"
        )
    return lines


def main() -> None:
    out = ["# Evaluation report", "", "Generated by `python -m eval.report` from the JSON files in this folder.", ""]
    def load(name):
        p = RESULTS / name
        return json.loads(p.read_text()) if p.exists() else None

    retr: list[str] = []
    rag: list[str] = []
    if base := load("retrieval_nolink.json"):
        retr = retrieval_section(base, load("retrieval_link.json"), load("retrieval_fast.json"))
        out += retr + [""]
    for name in ("rag_eval.json", "rag_eval_smoke.json"):
        if (RESULTS / name).exists():
            section = rag_section(json.loads((RESULTS / name).read_text()))[2:]  # README has its own heading
            if "smoke" in name:
                section = ["_Smoke run on a stratified subset of the golden set (`--limit`), not the full set:_", ""] + section
            rag += section + [""]
            out += rag_section(json.loads((RESULTS / name).read_text())) + [""]
    (RESULTS / "REPORT.md").write_text("\n".join(out))
    print("\n".join(out))
    _update_readme(retr, rag)


def _replace_between(text: str, tag: str, body: list[str]) -> str:
    start, end = f"<!-- {tag}:START -->", f"<!-- {tag}:END -->"
    if start not in text or end not in text:
        return text
    head, rest = text.split(start, 1)
    _, tail = rest.split(end, 1)
    return head + start + "\n" + "\n".join(body) + "\n" + end + tail


def _update_readme(retr: list[str], rag: list[str]) -> None:
    """Copy the generated tables into README.md so published numbers always match the result files."""
    readme = RESULTS.parent.parent / "README.md"
    text = readme.read_text()
    if retr:
        text = _replace_between(text, "RETRIEVAL", ["### " + retr[0].lstrip("# ")] + retr[1:])
    if rag:
        text = _replace_between(text, "RAG", rag)
    readme.write_text(text)


if __name__ == "__main__":
    main()
